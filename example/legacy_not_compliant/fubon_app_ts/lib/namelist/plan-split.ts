/**
 * 依「方案」分車——目前只有 528834 富士山親子這樣（Ina 2026-08-15 向 AM 確認）。
 *
 * 這個商品的團號結尾字母不是「第幾台車」，是**行程**：
 *   KK260817-528834    ＝ A／B 方案（同一個行程，差別只在含不含叢林巴士費用）
 *   KK260817-528834C   ＝ C／D 方案（多了水蜜桃吃到飽＋箱根釜飯午餐，或秋冬的長腳蟹＋柑橘）
 *
 * ⚠️ **團號上的「C」代表 C 和 D 兩個方案**，不是只有 C。
 *    這種不對稱最容易在半年後被誤讀成「D 方案沒地方去」，所以寫在這裡。
 *
 * 為什麼不能按人數均分：買 C／D 的客人被放到 AB 那台，會少掉採果與午餐；
 * 而名單看起來完全正常，要到現場才爆。
 *
 * 方案怎麼認：KKday 上的套餐名稱一律含「A方案：」「B方案：」「C方案：」「D方案：」，
 * 前面的促銷字樣（【1人成團｜保證出發】【暑假限定～日本水蜜桃吃到飽…】）會變，
 * 「X方案」這個結構不變 → 只認這個結構，不比對促銷文案。
 */

/**
 * 依商品編號決定要不要走方案分車。
 *   528834 富士山親子：AB 行程不標字母，CD 行程標 C
 *   573405           ：AB 行程標 A、CD 行程標 C（Ina 2026-08-15）
 * 兩支的差別只在「AB 那台標不標字母」，所以下面把「沒字母」與「A」視為同一件事。
 * ⚠️ 只有一個行程在跑的日子（例如淡季）團號根本不分 → 只有一列，自然不會走到這裡。
 */
export const PLAN_SPLIT_PRODUCTS = new Set(["528834", "573405"]);

/** 從套餐名稱取出方案字母；認不出回空字串（呼叫端要當成「不能自動分」）。 */
export function planOf(packageName: string): "A" | "B" | "C" | "D" | "" {
  const m = /([ABCD])\s*方案/.exec(String(packageName ?? "").toUpperCase().replace(/[Ａ-Ｄ]/g, (c) =>
    String.fromCharCode(c.charCodeAt(0) - 0xfee0)));
  return (m?.[1] as "A" | "B" | "C" | "D") ?? "";
}

/**
 * 團號結尾字母 → 這台車收哪些方案。
 *   "C"／"D"   → C、D 方案（多了採果與午餐那條行程）
 *   ""／"A"    → A、B 方案（573405 會寫 A 團，528834 不標，同一件事）
 * 認不得的字母（B…）回 null＝**不知道**，呼叫端要停下來，不能猜。
 *
 * 為什麼 "D" 也收（2026-08-15）：慣例上只有 C 行程會標字母、而且標 C，
 * 但大表實際出現過 KK261225-528834D、KK261228-528834D。
 * 該商品的人數欄本來就叫「ＣＤ」（C 與 D 同一台），所以 D 只可能是那台車。
 * 收下但**同時警告**——不警告的話這個筆誤會被程式默默吸收，永遠不會被改掉。
 */
export function plansOnCar(carLetter: string): string[] | null {
  const c = String(carLetter ?? "").toUpperCase();
  if (c === "C" || c === "D") return ["C", "D"];
  if (c === "" || c === "A") return ["A", "B"];
  return null;
}

/** 這個車別碼雖然認得，但不符慣例 → 要提醒人去大表改。 */
export function isOddPlanLetter(carLetter: string): boolean {
  return String(carLetter ?? "").toUpperCase() === "D";
}
