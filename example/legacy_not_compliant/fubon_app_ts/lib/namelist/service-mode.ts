/**
 * 要顯示的服務型態。不用車的行程回空字串——呼叫端一律用 `.filter(Boolean)` 串起來，
 * 空字串會自己消失，不需要在每個地方寫 if。
 *
 * @param usesVehicle 這個行程本身用不用車（不是「車資訊填了沒」）
 */
export function modeLabel(usesVehicle: boolean, serviceMode: string): string {
  return usesVehicle ? serviceMode : "";
}
